// jar entries to just drop
const MARKET_UNSTOCK = [
	'minecraft:bone_meal'
]

ServerEvents.recipes(event => {
	let stock = {}
	MARKET_STOCK.forEach(group => {
		group.items.forEach(id => {
			if (!stock[id]) stock[id] = group
		})
	})

	// kill jar entries for anything we sell ourselves, no dupes
	let removeIds = []
	event.forEachRecipe({ type: 'farmingforblockheads:market' }, r => {
		let result = r.json.get('result')
		if (!result || !result.has('item')) return
		let item = String(result.get('item').getAsString())
		if (stock[item] || MARKET_UNSTOCK.includes(item)) removeIds.push(String(r.getId()))
	})
	removeIds.forEach(id => event.remove({ id: id }))

	let added = 0
	Object.keys(stock).forEach(id => {
		let group = stock[id]
		let price = MARKET_CURRENCY[group.currency]
		event.custom({
			type: 'farmingforblockheads:market',
			category: group.tab,
			preset: 'fabled_wylds:market',
			result: { item: id },
			payment: { ingredient: { item: price.item }, count: price.count }
		}).id('fabled_wylds:market/' + id.replace(':', '/'))
		added++
	})

	console.info('[market] removed ' + removeIds.length + ' jar entries, added ' + added)
})
